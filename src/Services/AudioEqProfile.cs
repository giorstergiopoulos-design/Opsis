        // ---- Equalizer APO: εξαγωγή ------------------------------------------------------------------------------

        /// <summary>
        /// Κείμενο Equalizer APO. Ίδιος αλγόριθμος με το toEqualizerApo του Waveframe: το preamp αναιρεί τη μεγαλύτερη ενίσχυση
        /// (ζώνη ή ζώνη+bass shelf) ώστε η έξοδος να μην ψαλιδίζει· μία γραμμή Filter ανά ενεργή ζώνη, shelves στα άκρα.
        /// </summary>
        public string ToEqualizerApo()
        {
            var bands = Bands.Take(10).Select(Clamp).ToList();
            while (bands.Count < 10) bands.Add(0);
            double bass = Clamp(BassBoostDb);
            double maxBoost = 0;
            for (int i = 0; i < 10; i++) maxBoost = Math.Max(maxBoost, bands[i] + (i <= 2 ? bass : 0));
            maxBoost = Math.Max(maxBoost, Math.Max(bass, 0));
            double preamp = maxBoost <= 0 ? 0 : -Math.Ceiling(maxBoost * 10) / 10.0;      // (no negative zero: "-0.0")

            var sb = new StringBuilder();
            sb.Append("# ").Append(Sanitize(Name.Length > 0 ? Name : "Opsis EQ")).Append(" — generated by Opsis (Audio Enhancement)\r\n");
            sb.Append("Preamp: ").Append(F(preamp)).Append(" dB\r\n");
            int n = 1;
            for (int i = 0; i < 10; i++)
            {
                if (Math.Abs(bands[i]) < 0.05) continue;
                string type = i == 0 ? "LSC" : i == 9 ? "HSC" : "PK";
                double q = type == "PK" ? 1.41 : 0.70;
                sb.Append($"Filter {n++}: ON {type} Fc {Frequencies[i]} Hz Gain {F(bands[i])} dB Q {q.ToString("0.00", CultureInfo.InvariantCulture)}\r\n");
            }
            if (Math.Abs(bass) >= 0.05) sb.Append($"Filter {n++}: ON LSC Fc 100 Hz Gain {F(bass)} dB Q 0.70\r\n");
            foreach (var extra in ExtraLines) sb.Append(extra).Append("\r\n");
            return sb.ToString();
        }

        private static double Clamp(double v) => Math.Clamp(v, -MaxGainDb, MaxGainDb);
        private static string F(double v) => (Math.Round(v * 10) / 10.0).ToString("0.0", CultureInfo.InvariantCulture);
        private static string Sanitize(string s) => Regex.Replace(s, @"[\r\n]+", " ");

        // ---- Equalizer APO: εισαγωγή -----------------------------------------------------------------------------

        private static readonly Regex PreampRx = new(@"^Preamp:\s*(-?\d+(?:\.\d+)?)\s*dB$", RegexOptions.IgnoreCase | RegexOptions.Compiled);
        private static readonly Regex FilterRx = new(@"^Filter\s*\d*:\s*ON\s+(PK|LSC|HSC|LS|HS)\s+Fc\s+(\d+(?:\.\d+)?)\s*Hz\s+Gain\s+(-?\d+(?:\.\d+)?)\s*dB(?:\s+Q\s+(\d+(?:\.\d+)?))?\s*$", RegexOptions.IgnoreCase | RegexOptions.Compiled);

        /// <summary>
        /// Διαβάζει ΜΟΝΟ γραμμές Preamp/Filter (ON, τύπου PK/LSC/HSC). Οτιδήποτε άλλο (Include, Convolution, VSTPlugin, Copy, Channel...)
        /// αγνοείται — ένα εισαγόμενο αρχείο δεν μπορεί ποτέ να φορτώσει άλλα αρχεία ή πρόσθετα στο σύστημα ήχου του χρήστη.
        /// Φίλτρα που πέφτουν πάνω στις 10 συχνότητες γίνονται ζώνες· τα υπόλοιπα κρατιούνται ως ExtraLines.
        /// </summary>
        public static AudioEqProfile FromEqualizerApo(string text, string name = "Imported")
        {
            var p = new AudioEqProfile { Name = name };
            double preamp = 0; bool sawPreamp = false;
            var filters = new List<(string Type, double Fc, double Gain, double Q, string Line)>();
            foreach (var raw in text.Split('\n'))
            {
                string line = raw.Trim();
                var pm = PreampRx.Match(line);
                if (pm.Success) { preamp = double.Parse(pm.Groups[1].Value, CultureInfo.InvariantCulture); sawPreamp = true; continue; }
                var fm = FilterRx.Match(line);
                if (!fm.Success) continue;
                double fc = double.Parse(fm.Groups[2].Value, CultureInfo.InvariantCulture), gain = double.Parse(fm.Groups[3].Value, CultureInfo.InvariantCulture);
                double q = fm.Groups[4].Success ? double.Parse(fm.Groups[4].Value, CultureInfo.InvariantCulture) : 0.7;
                if (fc < 10 || fc > 24000 || Math.Abs(gain) > 30 || q is < 0.05 or > 50) continue;      // παράλογες τιμές: αγνοούνται
                filters.Add((fm.Groups[1].Value.ToUpperInvariant(), fc, gain, q, line));
            }
            foreach (var f in filters)
            {
                int idx = Array.IndexOf(Frequencies, (int)Math.Round(f.Fc));
                bool standardShape = (idx == 0 && f.Type is "LSC" or "LS") || (idx == 9 && f.Type is "HSC" or "HS") || (idx > 0 && idx < 9 && f.Type == "PK");
                if (idx >= 0 && Math.Abs(f.Fc - Frequencies[idx]) < 0.5 && standardShape && p.Bands[idx] == 0) p.Bands[idx] = Clamp(f.Gain);
                else p.ExtraLines.Add(Rebuild(f.Type, f.Fc, f.Gain, f.Q));
            }
            _ = preamp; _ = sawPreamp;     // το preamp υπολογίζεται ξανά από τα φίλτρα κατά την εξαγωγή/εφαρμογή (headroom)
            return p;
        }

        private static string Rebuild(string type, double fc, double gain, double q) =>
            $"Filter: ON {type} Fc {fc.ToString("0.##", CultureInfo.InvariantCulture)} Hz Gain {F(gain)} dB Q {q.ToString("0.00", CultureInfo.InvariantCulture)}";

        // ---- Waveframe preset JSON ({ name, bands[10], bassBoost, ... }) ---------------------------------------------

        public static AudioEqProfile? FromWaveframeJson(string json)
        {
            try
            {
                using var doc = JsonDocument.Parse(json);
                JsonElement root = doc.RootElement;
                if (root.ValueKind == JsonValueKind.Array && root.GetArrayLength() > 0) root = root[0];       // λίστα presets: το πρώτο
                if (root.ValueKind != JsonValueKind.Object || !root.TryGetProperty("bands", out var bands) || bands.ValueKind != JsonValueKind.Array) return null;
                var p = new AudioEqProfile { Name = root.TryGetProperty("name", out var n) && n.ValueKind == JsonValueKind.String ? n.GetString() ?? "Waveframe" : "Waveframe" };
                int i = 0;
                foreach (var b in bands.EnumerateArray())
                {
                    if (i >= 10) break;
                    if (b.ValueKind == JsonValueKind.Number) p.Bands[i] = Clamp(b.GetDouble());
                    i++;
                }
                if (i < 10 && i == 0) return null;
                if (root.TryGetProperty("bassBoost", out var bb) && bb.ValueKind == JsonValueKind.Number) p.BassBoostDb = Clamp(bb.GetDouble());
                return p;
            }
            catch (JsonException) { return null; }
        }

        /// <summary>Αυτόματη αναγνώριση: JSON (Waveframe) ή κείμενο Equalizer APO. null αν δεν περιέχει τίποτα χρήσιμο.</summary>
        public static AudioEqProfile? Import(string content, string fallbackName)
        {
            string trimmed = content.TrimStart('﻿', ' ', '\t', '\r', '\n');
            if (trimmed.StartsWith('{') || trimmed.StartsWith('['))
            {
                var j = FromWaveframeJson(trimmed);
                if (j != null) { if (string.IsNullOrWhiteSpace(j.Name)) j.Name = fallbackName; return j; }
                return null;
            }
            var apo = FromEqualizerApo(content, fallbackName);
            return apo.IsFlat && !content.Contains("Filter", StringComparison.OrdinalIgnoreCase) ? null : apo;
        }
    }
