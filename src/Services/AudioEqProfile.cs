    /// <summary>
    /// Προφίλ ισοσταθμιστή 10 ζωνών, ίδιο με του Waveframe (32 Hz ... 16 kHz, ±12 dB). Εφαρμόζεται ΣΕ ΟΛΟ ΤΟ ΣΥΣΤΗΜΑ μέσω Equalizer APO
    /// (βλ. <see cref="EqualizerApoService.ApplyProfile"/>) και ανταλλάσσεται με το Waveframe: το Waveframe εξάγει .txt (Equalizer APO) ή
    /// preset JSON και το Opsis τα εισάγει. Καθαρή λογική, χωρίς UI/registry: δοκιμάζεται με unit tests.
    /// </summary>
    public sealed class AudioEqProfile
    {
        public static readonly int[] Frequencies = { 32, 64, 125, 250, 500, 1000, 2000, 4000, 8000, 16000 };
        public const double MaxGainDb = 12;

        public string Name { get; set; } = "";
        public double[] Bands { get; set; } = new double[10];
        public double BassBoostDb { get; set; }
        /// <summary>Γραμμές Equalizer APO που δεν αντιστοιχούν στις 10 ζώνες (π.χ. από εισαγωγή): περνούν αυτούσιες αφού καθαριστούν.</summary>
        public List<string> ExtraLines { get; set; } = new();

        public bool IsFlat => Bands.All(b => Math.Abs(b) < 0.05) && Math.Abs(BassBoostDb) < 0.05 && ExtraLines.Count == 0;

        public AudioEqProfile Clone() => new() { Name = Name, Bands = (double[])Bands.Clone(), BassBoostDb = BassBoostDb, ExtraLines = new List<string>(ExtraLines) };

        /// <summary>Τα 16 presets του Waveframe (ίδιες τιμές), για κοινή εμπειρία ανάμεσα στις δύο εφαρμογές.</summary>
